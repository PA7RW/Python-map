
#Comparison operators are something you'll use forever no matter what programming language you code in. 
# Apart from If/Else statements and loops, they're possibly the most used things in all programming.
# voorbeelden:
# Equal to ==
# Not Equal To !=
# Greater Than >
# Greater Than or Equal To >=
# Less Than <
# Less Than or Equal To <=

print(5 > 1)
print(5 < 1)
print(5 >= 1)
print(5 <= 1)
print(5 == 1)
print(5 != 1)

# Print the results with descriptive labels
print(f"5 == 1: {5 == 1}")
print(f"5 != 1: {5 != 1}")
print(f"5 > 1: {5 > 1}")
print(f"5 >= 1: {5 >= 1}")
print(f"5 < 1: {5 < 1}")
print(f"5 <= 1: {5 <= 1}")