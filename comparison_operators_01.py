
# Vergelijkingsoperatoren (comparison operators) zul je altijd blijven gebruiken, ongeacht in welke programmeertaal je codeert. 
# Buiten if/else-statements en lussen (loops) zijn dit waarschijnlijk de meest gebruikte elementen in programmeren.
# Voorbeelden:
# Gelijk aan: ==
# Niet gelijk aan: !=
# Groter dan: >
# Groter dan of gelijk aan: >=
# Kleiner dan: <
# Kleiner dan of gelijk aan: <=

print(5 > 1)
print(5 < 1)
print(5 >= 1)
print(5 <= 1)
print(5 == 1)
print(5 != 1)

# Print de resultaten met duidelijke labels
print(f"5 == 1: {5 == 1}")
print(f"5 != 1: {5 != 1}")
print(f"5 > 1: {5 > 1}")
print(f"5 >= 1: {5 >= 1}")
print(f"5 < 1: {5 < 1}")
print(f"5 <= 1: {5 <= 1}")
